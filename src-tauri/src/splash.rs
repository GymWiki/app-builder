//! Splash-scherm zonder extra pakketten: een effen kleur en (optioneel) het logo in het midden, voor Android en iOS.
//! Schrijft alleen de bestanden die `flutter create` zelf aanmaakt (launch_background.xml, LaunchScreen.storyboard, LaunchImage).
//! Beperking: Android 12+ toont altijd het app-icoon op de gekozen kleur (systeemregel); het logo geldt daar dus niet apart.

use crate::error::{AppError, AppResult};
use image::imageops::FilterType;
use std::path::Path;

pub fn valid_hex(s: &str) -> bool {
    crate::studio_tools::valid_hex(s)
}

fn rgb(hex: &str) -> (u8, u8, u8) {
    let v = |i: usize| u8::from_str_radix(&hex[i..i + 2], 16).unwrap_or(255);
    (v(1), v(3), v(5))
}

pub fn android_background(hex: &str, logo: bool) -> String {
    let logo_item = if logo { "\n    <item>\n        <bitmap android:gravity=\"center\" android:src=\"@drawable/splash_logo\" />\n    </item>" } else { "" };
    format!(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by Studio (Assets > Splash screen). -->\n<layer-list xmlns:android=\"http://schemas.android.com/apk/res/android\">\n    <item>\n        <shape android:shape=\"rectangle\">\n            <solid android:color=\"{}\" />\n        </shape>\n    </item>{logo_item}\n</layer-list>\n",
        hex.to_uppercase()
    )
}

pub fn android_v31_styles(hex: &str) -> String {
    format!(
        "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by Studio: Android 12+ shows the app icon on this color. -->\n<resources>\n    <style name=\"LaunchTheme\" parent=\"@android:style/Theme.Light.NoTitleBar\">\n        <item name=\"android:windowBackground\">@drawable/launch_background</item>\n        <item name=\"android:windowSplashScreenBackground\">{}</item>\n    </style>\n</resources>\n",
        hex.to_uppercase()
    )
}

/// Zet de achtergrondkleur in het iOS-launchscherm; `None` als het bestand een eigen vorm heeft.
pub fn storyboard_with_color(text: &str, hex: &str) -> Option<String> {
    let key = "<color key=\"backgroundColor\" ";
    let start = text.find(key)?;
    let end = start + text[start..].find("/>")? + 2;
    let (r, g, b) = rgb(hex);
    let f = |c: u8| format!("{:.3}", c as f64 / 255.0);
    Some(format!("{}<color key=\"backgroundColor\" red=\"{}\" green=\"{}\" blue=\"{}\" alpha=\"1\" colorSpace=\"custom\" customColorSpace=\"sRGB\"/>{}", &text[..start], f(r), f(g), f(b), &text[end..]))
}

fn save(img: &image::RgbaImage, w: u32, h: u32, path: &Path) -> AppResult<()> {
    if let Some(d) = path.parent() {
        std::fs::create_dir_all(d)?;
    }
    image::imageops::resize(img, w, h, FilterType::Lanczos3)
        .save_with_format(path, image::ImageFormat::Png)
        .map_err(|e| AppError::CommandFailed(format!("saving splash logo: {e}")))
}

#[derive(Debug, Default, serde::Serialize, PartialEq)]
pub struct SplashReport {
    pub written: Vec<String>,
    pub warnings: Vec<String>,
}

/// Past het splash-scherm toe. `logo` = pad naar een PNG/JPG (bv. `store/icon-512.png`).
pub fn apply(dir: &Path, hex: &str, logo: Option<&Path>) -> AppResult<SplashReport> {
    if !valid_hex(hex) {
        return Err(AppError::Invalid("color must look like #4F46E5".into()));
    }
    let img = match logo {
        Some(p) => Some(image::open(p).map_err(|e| AppError::Invalid(format!("could not read the logo: {e}")))?.to_rgba8()),
        None => None,
    };
    let mut rep = SplashReport::default();
    let mut put = |rel: &str, content: String| -> AppResult<()> {
        let p = dir.join(rel);
        if let Some(d) = p.parent() {
            std::fs::create_dir_all(d)?;
        }
        std::fs::write(&p, content)?;
        rep.written.push(rel.to_string());
        Ok(())
    };
    if dir.join("android").is_dir() {
        let res = "android/app/src/main/res";
        for d in ["drawable", "drawable-v21"] {
            put(&format!("{res}/{d}/launch_background.xml"), android_background(hex, img.is_some()))?;
        }
        put(&format!("{res}/values-v31/styles.xml"), android_v31_styles(hex))?;
        if let Some(img) = &img {
            save(img, 288, 288, &dir.join(format!("{res}/drawable/splash_logo.png")))?;
            rep.written.push(format!("{res}/drawable/splash_logo.png"));
        }
    } else {
        rep.warnings.push("no_android".into());
    }
    let sb = dir.join("ios/Runner/Base.lproj/LaunchScreen.storyboard");
    if sb.is_file() {
        let text = std::fs::read_to_string(&sb)?;
        match storyboard_with_color(&text, hex) {
            Some(mut new) => {
                if let Some(img) = &img {
                    let set = "ios/Runner/Assets.xcassets/LaunchImage.imageset";
                    for (name, px) in [("LaunchImage.png", 168u32), ("LaunchImage@2x.png", 336), ("LaunchImage@3x.png", 504)] {
                        save(img, px, px, &dir.join(format!("{set}/{name}")))?;
                    }
                    // het beeld is vierkant: de afmetingen in het launchscherm kloppen dan ook
                    if let Some(i) = new.find("<image name=\"LaunchImage\"") {
                        let e = i + new[i..].find("/>").unwrap_or(0) + 2;
                        new.replace_range(i..e, "<image name=\"LaunchImage\" width=\"168\" height=\"168\"/>");
                    }
                    rep.written.push(format!("{set}/LaunchImage.png"));
                }
                std::fs::write(&sb, new)?;
                rep.written.push("ios/Runner/Base.lproj/LaunchScreen.storyboard".into());
            }
            None => rep.warnings.push("ios_custom".into()),
        }
    } else {
        rep.warnings.push("no_ios".into());
    }
    if rep.written.is_empty() {
        rep.warnings.push("no_platforms".into());
    }
    Ok(rep)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn android_files_carry_the_color_and_the_logo() {
        let a = android_background("#4f46e5", true);
        assert!(a.contains("#4F46E5") && a.contains("@drawable/splash_logo"));
        assert!(!android_background("#4f46e5", false).contains("splash_logo"));
        assert!(android_v31_styles("#112233").contains("windowSplashScreenBackground\">#112233"));
    }

    #[test]
    fn the_storyboard_color_is_replaced_in_place_or_left_alone() {
        let s = "<view>\n  <color key=\"backgroundColor\" red=\"1\" green=\"1\" blue=\"1\" alpha=\"1\" colorSpace=\"custom\" customColorSpace=\"sRGB\"/>\n</view>";
        let n = storyboard_with_color(s, "#FF0000").unwrap();
        assert!(n.contains("red=\"1.000\" green=\"0.000\" blue=\"0.000\"") && n.starts_with("<view>") && n.ends_with("</view>"));
        assert!(storyboard_with_color("<view/>", "#FF0000").is_none());
    }

    #[test]
    fn applying_writes_both_platforms_and_is_repeatable() {
        let d = std::env::temp_dir().join(format!("studio-splash-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(d.join("android/app/src/main/res")).unwrap();
        std::fs::create_dir_all(d.join("ios/Runner/Base.lproj")).unwrap();
        std::fs::write(d.join("ios/Runner/Base.lproj/LaunchScreen.storyboard"), "<color key=\"backgroundColor\" red=\"1\" green=\"1\" blue=\"1\" alpha=\"1\"/><image name=\"LaunchImage\" width=\"168\" height=\"185\"/>").unwrap();
        let logo = d.join("logo.png");
        image::RgbaImage::from_pixel(64, 64, image::Rgba([10, 20, 30, 255])).save(&logo).unwrap();
        let r = apply(&d, "#0D9488", Some(&logo)).unwrap();
        assert!(r.warnings.is_empty(), "{:?}", r.warnings);
        assert!(d.join("android/app/src/main/res/drawable/splash_logo.png").is_file());
        assert!(d.join("ios/Runner/Assets.xcassets/LaunchImage.imageset/LaunchImage@3x.png").is_file());
        let sb = std::fs::read_to_string(d.join("ios/Runner/Base.lproj/LaunchScreen.storyboard")).unwrap();
        assert!(sb.contains("height=\"168\""));
        let again = apply(&d, "#0D9488", Some(&logo)).unwrap();
        assert_eq!(again.written, r.written);
        assert!(apply(&d, "nope", None).is_err());
    }

    /// Echte controle op een door `flutter create` gemaakt project (`STUDIO_TEST_PROJECT`, een kopie): de bestanden blijven geldige XML.
    #[test]
    #[ignore]
    fn real_flutter_project_splash_files_are_valid_xml() {
        let d = std::path::PathBuf::from(std::env::var("STUDIO_TEST_PROJECT").unwrap());
        let logo = d.join("logo.png");
        image::RgbaImage::from_pixel(512, 512, image::Rgba([10, 20, 30, 255])).save(&logo).unwrap();
        let r = apply(&d, "#0D9488", Some(&logo)).unwrap();
        println!("{:?}", r);
        assert!(r.warnings.is_empty());
        for f in ["android/app/src/main/res/drawable/launch_background.xml", "android/app/src/main/res/values-v31/styles.xml", "ios/Runner/Base.lproj/LaunchScreen.storyboard"] {
            let o = std::process::Command::new("xmllint").args(["--noout", d.join(f).to_str().unwrap()]).output().unwrap();
            assert!(o.status.success(), "{f}: {}", String::from_utf8_lossy(&o.stderr));
        }
    }
}
