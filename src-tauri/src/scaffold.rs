//! Deterministisch scaffolden uit de blueprint (geen AI): `studio/blueprint.json`, thema, lege pagina's in de feature-first structuur,
//! routes en navigatie, modellen met voorbeelddata en de beschrijving in `STUDIO.md`. Idempotent: wat Claude later in pagina's, modellen of
//! voorbeelddata heeft gebouwd (herkenbaar aan het ontbreken van de `studio:placeholder`-markering) wordt nooit overschreven.

use crate::blueprint::{Blueprint, Field, Model, Page};
use crate::error::AppResult;
use std::path::Path;

pub const PLACEHOLDER: &str = "// studio:placeholder";

pub fn pascal(id: &str) -> String {
    id.split(['_', '-', ' ']).filter(|s| !s.is_empty()).map(|s| {
        let mut c = s.chars();
        c.next().map(|f| f.to_uppercase().collect::<String>() + c.as_str()).unwrap_or_default()
    }).collect()
}

fn lit(s: &str) -> String {
    format!("'{}'", s.replace('\\', "\\\\").replace('\'', "\\'").replace('$', "\\$").replace('\n', " "))
}

fn dart_type(f: &Field) -> String {
    match f.kind.as_str() {
        "int" => "int".into(),
        "double" => "double".into(),
        "bool" => "bool".into(),
        "date" => "DateTime".into(),
        _ => "String".into(), // text, enum (waarde als tekst), ref (id van het andere model)
    }
}

fn default_value(f: &Field) -> String {
    match f.kind.as_str() {
        "int" => "0".into(),
        "double" => "0".into(),
        "bool" => "false".into(),
        "date" => "DateTime.fromMillisecondsSinceEpoch(0)".into(),
        "enum" => lit(f.values.first().map(String::as_str).unwrap_or("")),
        _ => "''".into(),
    }
}

fn sample_literal(f: &Field, v: Option<&serde_json::Value>) -> String {
    let Some(v) = v else { return default_value(f) };
    match f.kind.as_str() {
        "int" => v.as_i64().map(|n| n.to_string()).unwrap_or_else(|| default_value(f)),
        "double" => v.as_f64().map(|n| format!("{n:?}")).unwrap_or_else(|| default_value(f)),
        "bool" => v.as_bool().map(|b| b.to_string()).unwrap_or_else(|| default_value(f)),
        "date" => v.as_str().map(|s| format!("DateTime.tryParse({}) ?? {}", lit(s), default_value(f))).unwrap_or_else(|| default_value(f)),
        _ => v.as_str().map(lit).unwrap_or_else(|| default_value(f)),
    }
}

pub fn model_dart(m: &Model) -> String {
    let cls = pascal(&m.id);
    let fields: String = m.fields.iter().map(|f| format!("  final {} {};\n", dart_type(f), f.name)).collect();
    let ctor: String = m.fields.iter().map(|f| format!("    required this.{},\n", f.name)).collect();
    let to_json: String = m.fields.iter().map(|f| if f.kind == "date" { format!("        '{0}': {0}.toIso8601String(),\n", f.name) } else { format!("        '{0}': {0},\n", f.name) }).collect();
    let from_json: String = m.fields.iter().map(|f| {
        let src = format!("json['{}']", f.name);
        match f.kind.as_str() {
            "date" => format!("      {}: DateTime.tryParse('${{{src}}}') ?? {},\n", f.name, default_value(f)),
            "int" => format!("      {}: ({src} as num?)?.toInt() ?? 0,\n", f.name),
            "double" => format!("      {}: ({src} as num?)?.toDouble() ?? 0,\n", f.name),
            "bool" => format!("      {}: ({src} as bool?) ?? false,\n", f.name),
            _ => format!("      {}: ({src} as String?) ?? {},\n", f.name, default_value(f)),
        }
    }).collect();
    let note = if m.fields.iter().any(|f| f.kind == "enum") {
        let l: Vec<String> = m.fields.iter().filter(|f| f.kind == "enum").map(|f| format!("{} is one of {}", f.name, f.values.join(", "))).collect();
        format!("/// {}.\n", l.join("; "))
    } else {
        String::new()
    };
    format!("{PLACEHOLDER}\n// Generated by Studio from studio/blueprint.json. Claude may extend this class; Studio will not overwrite it once this marker is gone.\n{note}class {cls} {{\n  const {cls}({{\n{ctor}  }});\n\n{fields}\n  factory {cls}.fromJson(Map<String, dynamic> json) => {cls}(\n{from_json}  );\n\n  Map<String, dynamic> toJson() => {{\n{to_json}      }};\n}}\n")
}

pub fn sample_dart(b: &Blueprint) -> String {
    let mut imports = String::new();
    let mut body = String::new();
    for m in &b.models {
        let cls = pascal(&m.id);
        imports.push_str(&format!("import '../models/{}.dart';\n", m.id));
        let rows: String = m
            .sample
            .iter()
            .map(|r| {
                let args: Vec<String> = m.fields.iter().map(|f| format!("{}: {}", f.name, sample_literal(f, r.get(&f.name)))).collect();
                format!("  {cls}({}),\n", args.join(", "))
            })
            .collect();
        body.push_str(&format!("\n/// Example {} shown in Studio's preview and in a fresh app.\nfinal sample{cls}s = <{cls}>[\n{rows}];\n", m.name));
    }
    format!("{PLACEHOLDER}\n// Generated by Studio from studio/blueprint.json (sample data for the live preview). Claude may extend it.\n{imports}{body}")
}

pub fn page_dart(p: &Page) -> String {
    let cls = format!("{}Screen", pascal(&p.id));
    let comps: String = p.components.iter().map(|c| format!("          {},\n", lit(c))).collect();
    format!(
        "{PLACEHOLDER}\nimport 'package:flutter/material.dart';\n\nimport '../../core/theme/tokens.dart';\n\n/// {}\nclass {cls} extends StatelessWidget {{\n  const {cls}({{super.key}});\n\n  @override\n  Widget build(BuildContext context) {{\n    final text = Theme.of(context).textTheme;\n    return Scaffold(\n      appBar: AppBar(title: const Text({})),\n      body: Padding(\n        padding: const EdgeInsets.all(AppSpacing.lg),\n        child: Column(\n          crossAxisAlignment: CrossAxisAlignment.start,\n          children: [\n            Text({}, style: text.bodyLarge),\n            const SizedBox(height: AppSpacing.md),\n            for (final part in const <String>[\n{comps}            ])\n              Padding(padding: const EdgeInsets.only(bottom: AppSpacing.sm), child: Text('• $part')),\n            const Spacer(),\n            const Center(child: Text('This page is being built…')),\n          ],\n        ),\n      ),\n    );\n  }}\n}}\n",
        p.purpose.replace('\n', " "),
        lit(&p.name),
        lit(&p.purpose),
    )
}

pub fn page_claude_md(p: &Page, b: &Blueprint) -> String {
    let models: Vec<String> = p.models.iter().filter_map(|id| b.models.iter().find(|m| &m.id == id)).map(|m| format!("{} ({})", pascal(&m.id), m.fields.iter().map(|f| f.name.as_str()).collect::<Vec<_>>().join(", "))).collect();
    let features: Vec<String> = p.features.iter().filter_map(|id| b.features.iter().find(|f| &f.id == id)).map(|f| f.title.clone()).collect();
    format!(
        "# {name}\nPurpose: {purpose}\nRoute: {route}\nKey parts: {components}\nModels: {models}\nFeatures: {features}\nExample data: lib/core/data/sample_data.dart (use it when kStudioPreview is true).\nKeep this page inside lib/features/{id}/; shared code goes in lib/core/.\n",
        name = p.name,
        purpose = p.purpose,
        route = p.route,
        components = p.components.join("; "),
        models = if models.is_empty() { "-".into() } else { models.join(", ") },
        features = if features.is_empty() { "-".into() } else { features.join("; ") },
        id = p.id,
    )
}

pub fn router_dart(b: &Blueprint) -> String {
    let imports: String = b.pages.iter().map(|p| format!("import '../../features/{0}/{0}_screen.dart';\n", p.id)).collect();
    let route = |p: &Page| format!("GoRoute(path: {}, builder: (context, state) => const {}Screen())", lit(&p.route), pascal(&p.id));
    let nav_ids: Vec<&str> = if b.navigation.order.is_empty() { b.pages.iter().map(|p| p.id.as_str()).collect() } else { b.navigation.order.iter().map(String::as_str).collect() };
    let in_nav = |p: &Page| b.navigation.kind != "single" && nav_ids.contains(&p.id.as_str());
    let nav_pages: Vec<&Page> = nav_ids.iter().filter_map(|id| b.pages.iter().find(|p| &p.id == id)).filter(|_| b.navigation.kind != "single").collect();
    let others: Vec<String> = b.pages.iter().filter(|p| !in_nav(p)).map(|p| format!("    {},\n", route(p))).collect();
    let shell = if nav_pages.is_empty() {
        String::new()
    } else {
        let routes: String = nav_pages.iter().map(|p| format!("        {},\n", route(p))).collect();
        format!("    ShellRoute(\n      builder: (context, state, child) => AppShell(location: state.uri.path, child: child),\n      routes: [\n{routes}      ],\n    ),\n")
    };
    let shell_import = if nav_pages.is_empty() { "" } else { "import 'app_shell.dart';\n" };
    let start = b.pages.iter().find(|p| p.route == "/").map(|p| p.route.as_str()).unwrap_or("/");
    format!("// Generated by Studio from studio/blueprint.json. A new page = a feature folder + a route here (Studio keeps the blueprint in sync).\nimport 'package:go_router/go_router.dart';\n\n{shell_import}{imports}\nfinal appRouter = GoRouter(\n  initialLocation: {},\n  routes: [\n{shell}{}  ],\n);\n", lit(start), others.concat())
}

pub fn shell_dart(b: &Blueprint) -> Option<String> {
    if b.navigation.kind == "single" {
        return None;
    }
    let ids: Vec<&str> = if b.navigation.order.is_empty() { b.pages.iter().map(|p| p.id.as_str()).collect() } else { b.navigation.order.iter().map(String::as_str).collect() };
    let pages: Vec<&Page> = ids.iter().filter_map(|id| b.pages.iter().find(|p| &p.id == id)).collect();
    if pages.is_empty() {
        return None;
    }
    let items: String = pages.iter().map(|p| format!("  _Item({}, {}, Icons.{}),\n", lit(&p.route), lit(&p.name), icon_for(p))).collect();
    let tabs = b.navigation.kind == "tabs";
    let body = if tabs {
        "    return Scaffold(\n      body: child,\n      bottomNavigationBar: NavigationBar(\n        selectedIndex: index,\n        onDestinationSelected: (i) => context.go(_items[i].route),\n        destinations: [for (final i in _items) NavigationDestination(icon: Icon(i.icon), label: i.label)],\n      ),\n    );".to_string()
    } else {
        "    return Scaffold(\n      key: _key,\n      drawer: NavigationDrawer(\n        selectedIndex: index,\n        onDestinationSelected: (i) {\n          Navigator.of(context).pop();\n          context.go(_items[i].route);\n        },\n        children: [for (final i in _items) NavigationDrawerDestination(icon: Icon(i.icon), label: Text(i.label))],\n      ),\n      body: Stack(children: [\n        child,\n        Positioned(\n          right: 4,\n          top: MediaQuery.of(context).padding.top + 4,\n          child: IconButton(icon: const Icon(Icons.menu), onPressed: () => _key.currentState?.openDrawer()),\n        ),\n      ]),\n    );".to_string()
    };
    let key = if tabs { "" } else { "  static final _key = GlobalKey<ScaffoldState>();\n" };
    Some(format!(
        "// Generated by Studio from studio/blueprint.json ({} navigation).\nimport 'package:flutter/material.dart';\nimport 'package:go_router/go_router.dart';\n\nclass _Item {{\n  const _Item(this.route, this.label, this.icon);\n  final String route;\n  final String label;\n  final IconData icon;\n}}\n\nconst _items = <_Item>[\n{items}];\n\nclass AppShell extends StatelessWidget {{\n  const AppShell({{super.key, required this.location, required this.child}});\n\n  final String location;\n  final Widget child;\n{key}\n  @override\n  Widget build(BuildContext context) {{\n    final found = _items.indexWhere((i) => i.route == location);\n    final index = found < 0 ? 0 : found;\n{body}\n  }}\n}}\n",
        b.navigation.kind
    ))
}

fn icon_for(p: &Page) -> &'static str {
    let t = format!("{} {}", p.id, p.name).to_lowercase();
    for (k, i) in [("setting", "settings"), ("instelling", "settings"), ("player", "group"), ("speler", "group"), ("profile", "person"), ("profiel", "person"), ("stat", "bar_chart"), ("chart", "bar_chart"), ("histor", "history"), ("search", "search"), ("zoek", "search"), ("list", "list"), ("lijst", "list"), ("home", "home"), ("start", "home")] {
        if t.contains(k) {
            return i;
        }
    }
    "circle"
}

pub fn studio_md_block(b: &Blueprint) -> String {
    let pages: String = b.pages.iter().map(|p| format!("- {} ({}): {}\n", p.name, p.route, p.purpose)).collect();
    let feats: String = b.features.iter().map(|f| format!("- {}{}\n", f.title, if f.status == "later" { " (later)" } else { "" })).collect();
    let assumptions: String = b.assumptions.iter().map(|a| format!("- {}\n", a.text)).collect();
    format!(
        "<!-- studio:blueprint:start -->\n## What this app is\n{}\n\nFor: {}\nLanguage: {}\n\n### Description from the owner\n{}\n\n### Features\n{}\n### Pages\n{}\n### Assumptions\n{}<!-- studio:blueprint:end -->\n",
        b.app.purpose, b.app.audience, b.app.language, b.app.description, feats, pages, assumptions
    )
}

fn replace_block(existing: &str, block: &str) -> String {
    match (existing.find("<!-- studio:blueprint:start -->"), existing.find("<!-- studio:blueprint:end -->")) {
        (Some(a), Some(z)) if z > a => format!("{}{}{}", &existing[..a], block.trim_end(), &existing[z + "<!-- studio:blueprint:end -->".len()..]),
        _ => format!("{}\n{}", existing.trim_end(), block),
    }
}

#[derive(Debug, Default, PartialEq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ScaffoldReport {
    pub written: Vec<String>,
    /// Bestanden die al door Claude of de gebruiker zijn aangepast en daarom met rust gelaten zijn.
    pub kept: Vec<String>,
    pub needs_pub_get: bool,
    pub notes: Vec<String>,
}

fn put(dir: &Path, rel: &str, content: &str, only_if_placeholder: bool, rep: &mut ScaffoldReport) -> AppResult<()> {
    let adapted;
    let content = if rel.ends_with(".dart") {
        adapted = crate::templates::adapt_material(dir, content);
        adapted.as_str()
    } else {
        content
    };
    let p = dir.join(rel);
    if let Ok(cur) = std::fs::read_to_string(&p) {
        if cur == content {
            return Ok(());
        }
        if only_if_placeholder && !cur.contains(PLACEHOLDER) {
            rep.kept.push(rel.to_string());
            return Ok(());
        }
    }
    if let Some(d) = p.parent() {
        std::fs::create_dir_all(d)?;
    }
    std::fs::write(&p, content)?;
    rep.written.push(rel.to_string());
    Ok(())
}

/// Schrijft alles wat uit de blueprint volgt. `project_dir` is een bestaand Flutter-project met het sjabloon (zie `templates`).
pub fn scaffold(dir: &Path, b: &Blueprint) -> AppResult<ScaffoldReport> {
    let caps = crate::blueprint::capabilities();
    let issues = crate::blueprint::validate(b, &caps);
    if !issues.is_empty() {
        return Err(crate::error::AppError::Invalid(format!("blueprint is not valid: {}", issues.join("; "))));
    }
    let mut rep = ScaffoldReport::default();
    put(dir, "studio/blueprint.json", &(serde_json::to_string_pretty(b)? + "\n"), false, &mut rep)?;
    put(dir, "studio/capabilities.json", crate::blueprint::CAPABILITIES, false, &mut rep)?;
    // De lege voorbeeldpagina van het sjabloon weg (alleen als hij nog ongewijzigd is en de blueprint geen eigen `home` heeft).
    let tpl_home = dir.join("lib/features/home/home_screen.dart");
    if !b.pages.iter().any(|p| p.id == "home") && std::fs::read_to_string(&tpl_home).is_ok_and(|t| t.contains("Your app starts here")) {
        let _ = std::fs::remove_dir_all(dir.join("lib/features/home"));
        rep.written.push("lib/features/home (removed)".into());
    }
    for m in &b.models {
        put(dir, &format!("lib/core/models/{}.dart", m.id), &model_dart(m), true, &mut rep)?;
    }
    if !b.models.is_empty() {
        put(dir, "lib/core/data/sample_data.dart", &sample_dart(b), true, &mut rep)?;
    }
    for p in &b.pages {
        put(dir, &format!("lib/features/{0}/{0}_screen.dart", p.id), &page_dart(p), true, &mut rep)?;
        put(dir, &format!("lib/features/{}/CLAUDE.md", p.id), &page_claude_md(p, b), false, &mut rep)?;
    }
    if let Some(shell) = shell_dart(b) {
        put(dir, "lib/core/navigation/app_shell.dart", &shell, false, &mut rep)?;
    } else {
        let _ = std::fs::remove_file(dir.join("lib/core/navigation/app_shell.dart"));
    }
    put(dir, "lib/core/navigation/app_router.dart", &router_dart(b), false, &mut rep)?;
    // thema uit de stijl (configuratiemotor, fase 13)
    let mut cfg = crate::config::load(dir);
    cfg.theme = crate::config::ThemeCfg { seed: Some(b.style.seed.to_uppercase()), font: Some(b.style.font.clone()), kit: Some(b.style.kit.clone()).filter(|k| k != "material") };
    let t = crate::config::apply(dir, &cfg)?;
    rep.needs_pub_get |= t.needs_pub_get;
    rep.written.extend(t.changed.iter().map(|c| c.file.clone()));
    rep.notes.extend(t.notes);
    // app-naam in de platformbestanden (best effort: ontbreken ze, dan is dat geen fout)
    let _ = crate::platform::set_app_name(dir, &b.app.name);
    // beschrijving en functies in het projectgeheugen
    let studio_md = dir.join("STUDIO.md");
    let existing = std::fs::read_to_string(&studio_md).unwrap_or_else(|_| format!("# {}\n", b.app.name));
    let new = replace_block(&existing, &studio_md_block(b));
    if new != existing {
        std::fs::write(&studio_md, new)?;
        rep.written.push("STUDIO.md".into());
    }
    Ok(rep)
}

fn snake(class: &str) -> String {
    let base = class.strip_suffix("Screen").or_else(|| class.strip_suffix("Page")).unwrap_or(class);
    let mut out = String::new();
    for (i, c) in base.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            out.push('_');
        }
        out.extend(c.to_lowercase());
    }
    out
}

fn humanize(id: &str) -> String {
    let words: Vec<String> = id.split('_').filter(|w| !w.is_empty()).map(|w| {
        let mut c = w.chars();
        c.next().map(|f| f.to_uppercase().collect::<String>() + c.as_str()).unwrap_or_default()
    }).collect();
    words.join(" ")
}

/// Houdt de blueprint gelijk met de echte pagina's (scherm-index): een later toegevoegde pagina komt erin, een verdwenen pagina gaat eruit.
/// `screens` = (klasse, route). Geeft `true` als er iets is bijgewerkt (blueprint en het blok in STUDIO.md).
pub fn sync_blueprint(dir: &Path, screens: &[(String, Option<String>)]) -> bool {
    let Ok(text) = std::fs::read_to_string(dir.join("studio/blueprint.json")) else { return false };
    let Ok(mut bp) = serde_json::from_str::<Blueprint>(&text) else { return false };
    let mut changed = false;
    for (class, route) in screens {
        let id = snake(class);
        if id.is_empty() || id.len() > 30 || bp.pages.iter().any(|p| p.id == id) || bp.pages.len() >= crate::blueprint::MAX_PAGES {
            continue;
        }
        let mut r = route.clone().filter(|r| r.starts_with('/') && !r.contains(':')).unwrap_or_else(|| format!("/{id}"));
        if bp.pages.iter().any(|p| p.route == r) {
            r = format!("/{id}");
        }
        if bp.pages.iter().any(|p| p.route == r) {
            continue;
        }
        bp.pages.push(Page { id: id.clone(), name: humanize(&id).chars().take(30).collect(), purpose: "Added later".into(), route: r, components: vec![], models: vec![], features: vec![], links: vec![] });
        changed = true;
    }
    // alleen wegnemen als er scherm-informatie is en het bestand echt weg is
    if !screens.is_empty() {
        let classes: Vec<String> = screens.iter().map(|(c, _)| snake(c)).collect();
        let before = bp.pages.len();
        bp.pages.retain(|p| classes.contains(&p.id) || dir.join(format!("lib/features/{0}/{0}_screen.dart", p.id)).is_file());
        if bp.pages.len() != before && !bp.pages.is_empty() {
            let ids: Vec<String> = bp.pages.iter().map(|p| p.id.clone()).collect();
            bp.navigation.order.retain(|i| ids.contains(i));
            for p in bp.pages.iter_mut() {
                p.links.retain(|l| ids.contains(l));
            }
            for f in bp.features.iter_mut() {
                f.pages.retain(|i| ids.contains(i));
            }
            changed = true;
        } else if bp.pages.len() != before {
            return false; // nooit alle pagina's weghalen
        }
    }
    if !changed {
        return false;
    }
    if !bp.pages.iter().any(|p| p.route == "/") {
        return false;
    }
    let _ = std::fs::write(dir.join("studio/blueprint.json"), serde_json::to_string_pretty(&bp).unwrap_or_default() + "\n");
    if let Ok(md) = std::fs::read_to_string(dir.join("STUDIO.md")) {
        let _ = std::fs::write(dir.join("STUDIO.md"), replace_block(&md, &studio_md_block(&bp)));
    }
    true
}

