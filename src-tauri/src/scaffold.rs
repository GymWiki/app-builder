    #[test]
    fn the_blueprint_follows_pages_added_or_removed_later() {
        let d = tmp("sync");
        let b = crate::blueprint::sample();
        scaffold(&d, &b).unwrap();
        let screens = |v: &[(&str, Option<&str>)]| v.iter().map(|(c, r)| (c.to_string(), r.map(String::from))).collect::<Vec<_>>();
        // een nieuwe pagina verschijnt in de blueprint, een tweede keer verandert er niets
        let all = screens(&[("HomeScreen", Some("/")), ("PlayersScreen", Some("/players")), ("SettingsScreen", Some("/settings")), ("MatchHistoryScreen", Some("/match-history"))]);
        assert!(sync_blueprint(&d, &all));
        let bp: Blueprint = serde_json::from_str(&std::fs::read_to_string(d.join("studio/blueprint.json")).unwrap()).unwrap();
        let added = bp.pages.iter().find(|p| p.id == "match_history").unwrap();
        assert_eq!((added.name.as_str(), added.route.as_str()), ("Match History", "/match-history"));
        assert!(std::fs::read_to_string(d.join("STUDIO.md")).unwrap().contains("Match History"));
        assert!(!sync_blueprint(&d, &all));
        // een verdwenen pagina (bestand weg én niet meer in de index) gaat eruit, ook uit de navigatie
        std::fs::remove_dir_all(d.join("lib/features/players")).unwrap();
        let fewer = screens(&[("HomeScreen", Some("/")), ("SettingsScreen", Some("/settings")), ("MatchHistoryScreen", Some("/match-history"))]);
        assert!(sync_blueprint(&d, &fewer));
        let bp: Blueprint = serde_json::from_str(&std::fs::read_to_string(d.join("studio/blueprint.json")).unwrap()).unwrap();
        assert!(!bp.pages.iter().any(|p| p.id == "players") && !bp.navigation.order.contains(&"players".to_string()));
        assert!(crate::blueprint::validate(&bp, &crate::blueprint::capabilities()).iter().all(|i| !i.contains("players")), "no dangling references");
        // zonder scherm-informatie gebeurt er niets
        assert!(!sync_blueprint(&d, &[]));
    }
