//! Toepasser "Data & Auth": deterministische code voor Supabase, Firebase of lokaal, zonder AI.
//! Genereert `lib/core/data/*` (init, auth-repository met voorbeelddata in de preview), een inlogscherm en de route ernaartoe.
//! Geen sleutels in bestanden: Supabase leest URL en publieke sleutel uit `--dart-define`. Eigen tabellen en logica blijven maatwerk (AI).

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq)]
#[serde(default)]
pub struct DataCfg {
    /// local | firebase | supabase | none (leeg = niet ingesteld)
    pub provider: String,
    /// email | anonymous | google | apple
    pub auth: Vec<String>,
}

pub const INIT: &str = "lib/core/data/studio_data.dart";
pub const AUTH: &str = "lib/core/data/auth_repository.dart";
pub const LOGIN: &str = "lib/features/auth/login_screen.dart";
pub const DELETE_SQL: &str = "studio/data/supabase_delete_user.sql";

/// Methodes die Studio zelf kan genereren; google/apple vragen native configuratie en een eigen account bij de winkel.
pub fn supported_methods(provider: &str) -> &'static [&'static str] {
    match provider {
        "supabase" | "firebase" => &["email", "anonymous"],
        _ => &[],
    }
}

pub fn has_accounts(c: &DataCfg) -> bool {
    matches!(c.provider.as_str(), "supabase" | "firebase") && c.auth.iter().any(|a| supported_methods(&c.provider).contains(&a.as_str()))
}

/// Pakketten die nodig zijn (voor `flutter pub add`, dat de juiste versies kiest).
pub fn packages(c: &DataCfg) -> Vec<&'static str> {
    match c.provider.as_str() {
        "supabase" => vec!["supabase_flutter"],
        "firebase" => {
            let mut v = vec!["firebase_core"];
            if has_accounts(c) {
                v.push("firebase_auth");
            }
            v
        }
        "local" => vec!["sqflite", "path"],
        _ => vec![],
    }
}

/// Meldingen over wat niet automatisch kan (sleutels voor de UI).
pub fn notes(c: &DataCfg) -> Vec<String> {
    let mut n = vec![];
    if c.auth.iter().any(|a| a == "google" || a == "apple") && matches!(c.provider.as_str(), "supabase" | "firebase") {
        n.push("auth_social_manual".into());
    }
    if c.provider == "firebase" {
        n.push("firebase_options".into());
    }
    if c.provider == "supabase" && has_accounts(c) {
        n.push("supabase_delete_sql".into());
    }
    if !c.auth.is_empty() && c.provider == "local" {
        n.push("local_no_accounts".into());
    }
    n
}

pub fn init_dart(c: &DataCfg) -> Option<String> {
    Some(match c.provider.as_str() {
        "supabase" => "import 'package:supabase_flutter/supabase_flutter.dart';\n\nimport '../preview_mode.dart';\n\n\
             // Public project settings, passed with --dart-define (never written into files).\n\
             const _url = String.fromEnvironment('SUPABASE_URL');\n\
             const _anonKey = String.fromEnvironment('SUPABASE_ANON_KEY');\n\n\
             /// Generated by Studio from studio/config.json. Called from main() before runApp.\n\
             Future<void> initStudioData() async {\n  \
             if (kStudioPreview || _url.isEmpty || _anonKey.isEmpty) return;\n  \
             await Supabase.initialize(url: _url, anonKey: _anonKey);\n}\n"
            .to_string(),
        "firebase" => "import 'package:firebase_core/firebase_core.dart';\n\nimport '../preview_mode.dart';\n\n\
             /// Generated by Studio from studio/config.json. Called from main() before runApp.\n\
             /// Run `flutterfire configure` once (Firebase sign-in on your computer) so the platform settings exist.\n\
             Future<void> initStudioData() async {\n  \
             if (kStudioPreview) return;\n  \
             await Firebase.initializeApp();\n}\n"
            .to_string(),
        "local" => "/// Generated by Studio from studio/config.json. The app stores its data on the phone (sqflite); nothing to start.\n\
             Future<void> initStudioData() async {}\n"
            .to_string(),
        _ => return None,
    })
}

pub fn auth_dart(c: &DataCfg) -> Option<String> {
    if !has_accounts(c) {
        return None;
    }
    let email = c.auth.iter().any(|a| a == "email");
    let anon = c.auth.iter().any(|a| a == "anonymous");
    let sb = c.provider == "supabase";
    let import = if sb { "import 'package:supabase_flutter/supabase_flutter.dart';" } else { "import 'package:firebase_auth/firebase_auth.dart';" };
    let mut abs = String::new();
    let mut imp = String::new();
    let mut prev = String::new();
    if email {
        abs.push_str("  Future<void> signIn(String email, String password);\n  Future<void> signUp(String email, String password);\n");
        prev.push_str("  @override\n  Future<void> signIn(String email, String password) async {}\n  @override\n  Future<void> signUp(String email, String password) async {}\n");
        imp.push_str(&if sb {
            "  @override\n  Future<void> signIn(String email, String password) async {\n    await Supabase.instance.client.auth.signInWithPassword(email: email, password: password);\n  }\n\n  @override\n  Future<void> signUp(String email, String password) async {\n    await Supabase.instance.client.auth.signUp(email: email, password: password);\n  }\n\n".to_string()
        } else {
            "  @override\n  Future<void> signIn(String email, String password) async {\n    await FirebaseAuth.instance.signInWithEmailAndPassword(email: email, password: password);\n  }\n\n  @override\n  Future<void> signUp(String email, String password) async {\n    await FirebaseAuth.instance.createUserWithEmailAndPassword(email: email, password: password);\n  }\n\n".to_string()
        });
    }
    if anon {
        abs.push_str("  Future<void> signInAnonymously();\n");
        prev.push_str("  @override\n  Future<void> signInAnonymously() async {}\n");
        imp.push_str(if sb {
            "  @override\n  Future<void> signInAnonymously() async {\n    await Supabase.instance.client.auth.signInAnonymously();\n  }\n\n"
        } else {
            "  @override\n  Future<void> signInAnonymously() async {\n    await FirebaseAuth.instance.signInAnonymously();\n  }\n\n"
        });
    }
    let (out, del, signed) = if sb {
        (
            "await Supabase.instance.client.auth.signOut();",
            "// Needs the SQL function in studio/data/supabase_delete_user.sql (apply it once to your Supabase project).\n    await Supabase.instance.client.rpc('delete_user');\n    await Supabase.instance.client.auth.signOut();",
            "Supabase.instance.client.auth.currentSession != null",
        )
    } else {
        ("await FirebaseAuth.instance.signOut();", "await FirebaseAuth.instance.currentUser?.delete();", "FirebaseAuth.instance.currentUser != null")
    };
    Some(format!(
        "import 'package:flutter_riverpod/flutter_riverpod.dart';\n{import}\n\nimport '../preview_mode.dart';\n\n\
         /// Generated by Studio from studio/config.json: sign-in, sign-out and \"delete my account\" (required by both stores).\n\
         /// Screens use authRepositoryProvider; they never talk to the backend directly.\n\
         abstract class AuthRepository {{\n{abs}  Future<void> signOut();\n  Future<void> deleteAccount();\n  bool get signedIn;\n}}\n\n\
         class BackendAuthRepository implements AuthRepository {{\n{imp}  @override\n  Future<void> signOut() async {{\n    {out}\n  }}\n\n  \
         @override\n  Future<void> deleteAccount() async {{\n    {del}\n  }}\n\n  @override\n  bool get signedIn => {signed};\n}}\n\n\
         /// Used by Studio's live preview: nobody has to sign in and nothing is sent anywhere.\n\
         class PreviewAuthRepository implements AuthRepository {{\n{prev}  @override\n  Future<void> signOut() async {{}}\n  @override\n  Future<void> deleteAccount() async {{}}\n  @override\n  bool get signedIn => true;\n}}\n\n\
         final authRepositoryProvider = Provider<AuthRepository>((ref) => kStudioPreview ? PreviewAuthRepository() : BackendAuthRepository());\n"
    ))
}

pub fn login_dart(c: &DataCfg) -> Option<String> {
    if !has_accounts(c) {
        return None;
    }
    let email = c.auth.iter().any(|a| a == "email");
    let anon = c.auth.iter().any(|a| a == "anonymous");
    let mut fields = String::new();
    if email {
        fields.push_str(
            "          TextField(controller: _email, keyboardType: TextInputType.emailAddress, decoration: const InputDecoration(labelText: 'Email')),\n\
             \x20         const SizedBox(height: AppSpacing.sm),\n\
             \x20         TextField(controller: _password, obscureText: true, decoration: const InputDecoration(labelText: 'Password')),\n\
             \x20         const SizedBox(height: AppSpacing.md),\n\
             \x20         FilledButton(onPressed: () => _run(() => ref.read(authRepositoryProvider).signIn(_email.text.trim(), _password.text)), child: const Text('Sign in')),\n\
             \x20         TextButton(onPressed: () => _run(() => ref.read(authRepositoryProvider).signUp(_email.text.trim(), _password.text)), child: const Text('Create account')),\n",
        );
    }
    if anon {
        fields.push_str("          TextButton(onPressed: () => _run(() => ref.read(authRepositoryProvider).signInAnonymously()), child: const Text('Continue without an account')),\n");
    }
    Some(format!(
        "import 'package:flutter/material.dart';\nimport 'package:flutter_riverpod/flutter_riverpod.dart';\nimport 'package:go_router/go_router.dart';\n\n\
         import '../../core/data/auth_repository.dart';\nimport '../../core/theme/tokens.dart';\n\n\
         /// Generated by Studio from studio/config.json (Data & login). Edit the look freely; Studio only regenerates it when the login methods change.\n\
         class LoginScreen extends ConsumerStatefulWidget {{\n  const LoginScreen({{super.key}});\n\n  @override\n  ConsumerState<LoginScreen> createState() => _LoginScreenState();\n}}\n\n\
         class _LoginScreenState extends ConsumerState<LoginScreen> {{\n  final _email = TextEditingController();\n  final _password = TextEditingController();\n  String? _error;\n\n  \
         @override\n  void dispose() {{\n    _email.dispose();\n    _password.dispose();\n    super.dispose();\n  }}\n\n  \
         Future<void> _run(Future<void> Function() action) async {{\n    try {{\n      await action();\n      if (mounted) context.go('/');\n    }} catch (e) {{\n      if (mounted) setState(() => _error = 'That did not work. Check your details and try again.');\n    }}\n  }}\n\n  \
         @override\n  Widget build(BuildContext context) {{\n    return Scaffold(\n      appBar: AppBar(title: const Text('Sign in')),\n      body: Padding(\n        padding: const EdgeInsets.all(AppSpacing.md),\n        child: Column(\n          crossAxisAlignment: CrossAxisAlignment.stretch,\n          children: [\n{fields}          if (_error != null) Padding(padding: const EdgeInsets.only(top: AppSpacing.sm), child: Text(_error!, style: TextStyle(color: Theme.of(context).colorScheme.error))),\n          ],\n        ),\n      ),\n    );\n  }}\n}}\n"
    ))
}

