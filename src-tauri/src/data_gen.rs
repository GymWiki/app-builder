/// `void main() => runApp(X);` → start de gegevenslaag voor runApp. `None` = al zo of een eigen vorm (dan een melding).
pub fn wire_main(text: &str, import_line: &str) -> Option<String> {
    if text.contains("initStudioData") {
        return None;
    }
    let start = text.find("void main() => runApp(")?;
    let rest = &text[start + "void main() => runApp(".len()..];
    let end = rest.find(");")?;
    let arg = &rest[..end];
    let mut s = String::new();
    s.push_str(&text[..start]);
    s.push_str(&format!("Future<void> main() async {{\n  WidgetsFlutterBinding.ensureInitialized();\n  await initStudioData();\n  runApp({arg});\n}}"));
    s.push_str(&rest[end + 2..]);
    let at = s.rfind("\nimport ").map(|i| s[i + 1..].find('\n').map(|e| i + 1 + e + 1).unwrap_or(s.len())).unwrap_or(0);
    s.insert_str(at, &format!("{import_line}\n"));
    Some(s)
}

/// Voegt de route `/login` toe aan `appRouter`. `None` = al aanwezig of een eigen vorm.
pub fn wire_router(text: &str) -> Option<String> {
    if text.contains("LoginScreen") {
        return None;
    }
    let pos = text.find("routes: [")? + "routes: [".len();
    let mut s = String::new();
    s.push_str(&text[..pos]);
    s.push_str("\n    GoRoute(path: '/login', builder: (context, state) => const LoginScreen()),");
    s.push_str(&text[pos..]);
    let at = s.rfind("\nimport ").map(|i| s[i + 1..].find('\n').map(|e| i + 1 + e + 1).unwrap_or(s.len())).unwrap_or(0);
    s.insert_str(at, "import '../../features/auth/login_screen.dart';\n");
    Some(s)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg(p: &str, a: &[&str]) -> DataCfg {
        DataCfg { provider: p.into(), auth: a.iter().map(|s| s.to_string()).collect() }
    }

    #[test]
    fn packages_and_notes_follow_the_choice() {
        assert_eq!(packages(&cfg("supabase", &["email"])), vec!["supabase_flutter"]);
        assert_eq!(packages(&cfg("firebase", &["email"])), vec!["firebase_core", "firebase_auth"]);
        assert_eq!(packages(&cfg("firebase", &[])), vec!["firebase_core"]);
        assert!(packages(&cfg("none", &[])).is_empty());
        assert!(notes(&cfg("supabase", &["email", "google"])).contains(&"auth_social_manual".to_string()));
        assert!(notes(&cfg("local", &["email"])).contains(&"local_no_accounts".to_string()));
    }

    #[test]
    fn no_secret_ever_ends_up_in_the_generated_code() {
        let c = cfg("supabase", &["email", "anonymous"]);
        for t in [init_dart(&c).unwrap(), auth_dart(&c).unwrap(), login_dart(&c).unwrap()] {
            assert!(!t.contains("eyJ") && !t.contains("sbp_") && !t.contains("supabase.co"));
        }
        assert!(init_dart(&c).unwrap().contains("String.fromEnvironment('SUPABASE_ANON_KEY')"));
        assert!(auth_dart(&c).unwrap().contains("rpc('delete_user')") && auth_dart(&c).unwrap().contains("kStudioPreview"));
    }

    #[test]
    fn main_and_router_are_wired_once() {
        let m = "import 'package:flutter/material.dart';\nimport 'app.dart';\n\nvoid main() => runApp(const ProviderScope(child: App()));\n";
        let w = wire_main(m, "import 'core/data/studio_data.dart';").unwrap();
        assert!(w.contains("await initStudioData();") && w.contains("runApp(const ProviderScope(child: App()));") && w.contains("import 'core/data/studio_data.dart';"));
        assert!(wire_main(&w, "x").is_none());
        let r = "import 'package:go_router/go_router.dart';\n\nfinal appRouter = GoRouter(\n  routes: [\n    GoRoute(path: '/', builder: (c, s) => const Home()),\n  ],\n);\n";
        let w = wire_router(r).unwrap();
        assert!(w.contains("path: '/login'") && wire_router(&w).is_none());
        assert!(wire_main("void main() { runApp(x); }", "i").is_none(), "an own main() is never rewritten");
    }

    #[test]
    fn only_email_and_anonymous_are_generated() {
        assert!(login_dart(&cfg("supabase", &["google"])).is_none());
        assert!(login_dart(&cfg("local", &["email"])).is_none());
        let t = login_dart(&cfg("firebase", &["email"])).unwrap();
        assert!(t.contains("Create account") && !t.contains("without an account"));
    }

    /// Echte controle: de gegenereerde Dart-bestanden moeten syntactisch kloppen (`dart format` parseert zonder pakketten te hoeven ophalen).
    #[test]
    #[ignore]
    fn real_generated_dart_parses() {
        let dart = crate::proc::find("dart").expect("dart on PATH");
        let d = std::env::temp_dir().join(format!("studio-datagen-{}", std::process::id()));
        std::fs::create_dir_all(&d).unwrap();
        let mut n = 0;
        for (p, a) in [("supabase", vec!["email", "anonymous"]), ("firebase", vec!["email"]), ("supabase", vec!["email"]), ("local", vec![])] {
            let c = cfg(p, &a);
            for (i, t) in [init_dart(&c), auth_dart(&c), login_dart(&c)].into_iter().flatten().enumerate() {
                let f = d.join(format!("{p}_{}_{i}.dart", a.len()));
                std::fs::write(&f, t).unwrap();
                let o = crate::proc::run(&dart, &["format", "--output=none", f.to_str().unwrap()], None, std::time::Duration::from_secs(60)).unwrap();
                assert!(o.status == Some(0) || o.status == Some(1), "{}: {}", f.display(), o.combined());
                assert!(!o.combined().contains("Could not format"), "{}: {}", f.display(), o.combined());
                n += 1;
            }
        }
        println!("parsed {n} files");
    }
}
